# Read two inputs from the user and convert into integer (number)
x = int(input("Enter a number: "))
y = int(input("Enter second number: "))

# Add the values and display the result.
sum = x + y
print("Addition =", sum)

# Subtract the second value from the first and print the result.
diff = x - y
print("Difference =", diff)

# Multiply the values together and print the result.
product = x * y
print("Product =", product)

# Divide the first number by the second to get the quotient.
division = x / y
print("Division =", division)

